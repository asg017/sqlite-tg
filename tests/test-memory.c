// Memory-abuse harness for the extension, built against the vendored SQLite.
// Run under a memory checker (`make test-memory` runs it under ASan+LSan,
// `leaks -atExit`, and Guard Malloc), but it is also its own leak detector:
// both SQLite's allocator and tg's allocator are replaced with counting
// wrappers, and every statement asserts that the number of live tg
// allocations returns to what it was before the statement ran.
//
// Sections:
//   1. OK statements, one per ownership pattern (constructors, pointer
//      round-trips, each-vtabs, aggregates, the tg0 rtree table), each run
//      three ways: sqlite3_exec to completion; prepare -> step once -> reset
//      (abandons vtab cursors mid-iteration and unread result rows, so
//      xClose / value destructors fire early); then re-run to completion on
//      the same prepared statement.
//   2. Statements that must error, without crashing or leaking.
//   3. Deterministic corruption fuzzing: WKB seeds (generated by the
//      extension itself) and WKT/GeoJSON seeds are truncated at every
//      length, corrupted at every byte, and randomly mutated, then fed back
//      through every parse entry point in geomValue.
//   4. OOM sweep: the Nth tg allocation is forced to fail — for every N
//      until a full pass survives — and each cycle must end with zero live
//      tg allocations, proving every tg_geom_* == NULL branch in the
//      extension cleans up after itself.
//
// argv[1] optionally repeats section 1+2 N times to amplify slow leaks for
// tools without per-allocation reporting. TEST_MEMORY_FUZZ_ITERS and
// TEST_MEMORY_OOM_CAP scale sections 3 and 4.

// ───────────────────────── instrumented allocators ─────────────────────────

static long tg_live = 0;       // live allocations made by tg
static long long tg_total = 0; // total allocations made by tg, ever
static long oom_remaining = -1; // when >= 0: fail the tg allocation this many
                                // calls from now (once), then disarm. Scoped
                                // to tg's allocator so the OOM sweep exercises
                                // the extension's own error paths (every
                                // tg_geom_* == NULL branch in sqlite-tg.c)
                                // without tripping SQLITE_DEBUG asserts that
                                // assume SQLite's own allocations succeed.
static int oom_fired = 0;

static int oom_tick(void) {
  if (oom_remaining < 0) {
    return 0;
  }
  if (oom_remaining == 0) {
    oom_remaining = -1;
    oom_fired = 1;
    return 1;
  }
  oom_remaining--;
  return 0;
}

static void *tg_counted_malloc(size_t n) {
  if (oom_tick()) {
    return NULL;
  }
  void *p = malloc(n);
  if (p) {
    tg_live++;
    tg_total++;
  }
  return p;
}
static void *tg_counted_realloc(void *ptr, size_t n) {
  if (oom_tick()) {
    return NULL;
  }
  void *p = realloc(ptr, n);
  if (p && !ptr) {
    tg_live++;
    tg_total++;
  }
  return p;
}
static void tg_counted_free(void *ptr) {
  if (ptr) {
    tg_live--;
  }
  free(ptr);
}

// every statement must leave the live tg allocation count where it found it
static int check_balance(const char *what, long before) {
  if (tg_live != before) {
    fprintf(stderr, "❌ [%s] leaked %ld tg allocation(s)\n", what,
            tg_live - before);
    return 1;
  }
  return 0;
}

static int exec_ok(sqlite3 *db, const char *sql) {
  long before = tg_live;
  char *err = NULL;
  int rc = sqlite3_exec(db, sql, NULL, NULL, &err);
  if (rc != SQLITE_OK) {
    fprintf(stderr, "❌ [%s] failed: %s\n", sql, err ? err : sqlite3_errmsg(db));
    sqlite3_free(err);
    return 1;
  }
  return check_balance(sql, before);
}

// prepare, abandon after one step, then reset and run to completion
static int exec_lifecycle(sqlite3 *db, const char *sql) {
  long before = tg_live;
  sqlite3_stmt *stmt = NULL;
  int rc = sqlite3_prepare_v2(db, sql, -1, &stmt, NULL);
  if (rc != SQLITE_OK) {
    fprintf(stderr, "❌ [%s] prepare failed: %s\n", sql, sqlite3_errmsg(db));
    return 1;
  }
  rc = sqlite3_step(stmt);
  if (rc != SQLITE_ROW && rc != SQLITE_DONE) {
    fprintf(stderr, "❌ [%s] first step failed: %s\n", sql,
            sqlite3_errmsg(db));
    sqlite3_finalize(stmt);
    return 1;
  }
  sqlite3_reset(stmt);
  while ((rc = sqlite3_step(stmt)) == SQLITE_ROW) {
    // touch every column so result destructors and text conversions run
    for (int i = 0; i < sqlite3_column_count(stmt); i++) {
      sqlite3_column_text(stmt, i);
    }
  }
  if (rc != SQLITE_DONE) {
    fprintf(stderr, "❌ [%s] re-run after reset failed: %s\n", sql,
            sqlite3_errmsg(db));
    sqlite3_finalize(stmt);
    return 1;
  }
  sqlite3_finalize(stmt);
  return check_balance(sql, before);
}

// statements that must error, without crashing or leaking
static int exec_expect_error(sqlite3 *db, const char *sql) {
  long before = tg_live;
  char *err = NULL;
  int rc = sqlite3_exec(db, sql, NULL, NULL, &err);
  if (rc == SQLITE_OK) {
    fprintf(stderr, "❌ [%s] unexpectedly succeeded\n", sql);
    return 1;
  }
  sqlite3_free(err);
  return check_balance(sql, before);
}

// ─────────────────────────── corruption fuzzing ────────────────────────────
//
// Deterministic: a fixed-seed xorshift64 drives every mutation, so a crash
// reproduces by re-running the binary. Any outcome (rows or an error) is
// acceptable for a mutated input — what is not acceptable is a crash, an
// ASan report, or a tg allocation left behind.

static unsigned long long rng_state = 0x746727aa2b38a35bULL;
static unsigned long long rng_next(void) {
  rng_state ^= rng_state << 13;
  rng_state ^= rng_state >> 7;
  rng_state ^= rng_state << 17;
  return rng_state;
}

// seeds cover every geometry class, Z/M dims, empties, holes, and nesting
static const char *FUZZ_SEED_WKTS[] = {
    "POINT(1 2)",
    "POINT Z (1 2 3)",
    "POINT ZM (1 2 3 4)",
    "POINT EMPTY",
    "LINESTRING(0 0, 1 1, 2 0, 3 5)",
    "POLYGON((0 0, 10 0, 10 10, 0 10, 0 0), (1 1, 2 1, 2 2, 1 2, 1 1))",
    "MULTIPOINT(1 1, 2 2, 3 3)",
    "MULTILINESTRING((0 0, 1 1), (2 2, 3 3, 4 4))",
    "MULTIPOLYGON(((0 0, 1 0, 1 1, 0 0)), ((5 5, 6 5, 6 6, 5 5)))",
    "GEOMETRYCOLLECTION(POINT(1 1), LINESTRING(0 0, 1 1), GEOMETRYCOLLECTION(POINT(2 2)))",
};
static const char *FUZZ_SEED_GEOJSON[] = {
    "{\"type\": \"Point\", \"coordinates\": [1, 2]}",
    "{\"type\": \"Feature\", \"geometry\": {\"type\": \"Point\", "
    "\"coordinates\": [1, 2]}, \"properties\": {\"a\": [1, {\"b\": []}]}}",
    "{\"type\": \"FeatureCollection\", \"features\": [{\"type\": \"Feature\", "
    "\"geometry\": {\"type\": \"Point\", \"coordinates\": [1, 2]}, "
    "\"properties\": {}}]}",
    "{\"type\": \"MultiPolygon\", \"coordinates\": "
    "[[[[0, 0], [1, 0], [1, 1], [0, 0]]]]}",
};

// every parse entry point in geomValue, plus both index builds
static const char *FUZZ_QUERIES[] = {
    "select tg_to_wkt(?1)",
    "select tg_to_geojson(tg_geom(?1, 'natural'))",
    "select tg_memsize(tg_geom(?1, 'ystripes'))",
};
#define FUZZ_QUERY_COUNT (sizeof(FUZZ_QUERIES) / sizeof(FUZZ_QUERIES[0]))

static long fuzz_execs = 0;

// bind one mutated input to every fuzz query; outcome is ignored, balance
// and crash-freedom are the assertions
static int fuzz_feed(sqlite3_stmt **stmts, const void *data, int len,
                     int is_blob) {
  int failures = 0;
  for (int i = 0; i < FUZZ_QUERY_COUNT; i++) {
    long before = tg_live;
    if (is_blob) {
      sqlite3_bind_blob(stmts[i], 1, data, len, SQLITE_STATIC);
    } else {
      sqlite3_bind_text(stmts[i], 1, data, len, SQLITE_STATIC);
    }
    while (sqlite3_step(stmts[i]) == SQLITE_ROW) {
    }
    sqlite3_reset(stmts[i]);
    sqlite3_clear_bindings(stmts[i]);
    fuzz_execs++;
    if (tg_live != before) {
      fprintf(stderr,
              "❌ fuzz: [%s] leaked %ld tg allocation(s) on a %d-byte %s "
              "input\n",
              FUZZ_QUERIES[i], tg_live - before, len, is_blob ? "wkb" : "text");
      failures++;
    }
  }
  return failures;
}

// truncate at every length, corrupt every byte four ways, then random
// multi-byte mutations
static int fuzz_buffer(sqlite3_stmt **stmts, const unsigned char *seed,
                       int len, int is_blob, long random_iters) {
  int failures = 0;
  unsigned char *buf = malloc(len > 0 ? len : 1);
  for (int n = 0; n < len && !failures; n++) {
    failures += fuzz_feed(stmts, seed, n, is_blob);
  }
  for (int pos = 0; pos < len && !failures; pos++) {
    static const unsigned char twiddles[] = {0x00, 0xff, 0x80, 0x01};
    memcpy(buf, seed, len);
    for (int t = 0; t < sizeof(twiddles) && !failures; t++) {
      buf[pos] = seed[pos] ^ twiddles[t];
      failures += fuzz_feed(stmts, buf, len, is_blob);
    }
  }
  for (long i = 0; i < random_iters && !failures; i++) {
    memcpy(buf, seed, len);
    int edits = 1 + rng_next() % 8;
    for (int e = 0; e < edits; e++) {
      buf[rng_next() % len] = rng_next() & 0xff;
    }
    // half the time also truncate, so mutations compound with short reads
    int n = (rng_next() & 1) ? len : (int)(rng_next() % (len + 1));
    failures += fuzz_feed(stmts, buf, n, is_blob);
  }
  free(buf);
  return failures;
}

static int fuzz(sqlite3 *db, long random_iters) {
  int failures = 0;
  sqlite3_stmt *stmts[FUZZ_QUERY_COUNT] = {NULL};
  for (int i = 0; i < FUZZ_QUERY_COUNT; i++) {
    if (sqlite3_prepare_v2(db, FUZZ_QUERIES[i], -1, &stmts[i], NULL) !=
        SQLITE_OK) {
      fprintf(stderr, "❌ fuzz: cannot prepare [%s]: %s\n", FUZZ_QUERIES[i],
              sqlite3_errmsg(db));
      failures++;
      goto done;
    }
  }

  // WKB seeds come from the extension itself: round-trip each WKT seed
  {
    sqlite3_stmt *to_wkb = NULL;
    if (sqlite3_prepare_v2(db, "select tg_to_wkb(?1)", -1, &to_wkb, NULL) !=
        SQLITE_OK) {
      fprintf(stderr, "❌ fuzz: cannot prepare tg_to_wkb: %s\n",
              sqlite3_errmsg(db));
      failures++;
      goto done;
    }
    for (int s = 0; s < sizeof(FUZZ_SEED_WKTS) / sizeof(FUZZ_SEED_WKTS[0]);
         s++) {
      sqlite3_bind_text(to_wkb, 1, FUZZ_SEED_WKTS[s], -1, SQLITE_STATIC);
      if (sqlite3_step(to_wkb) != SQLITE_ROW) {
        fprintf(stderr, "❌ fuzz: tg_to_wkb('%s') failed: %s\n",
                FUZZ_SEED_WKTS[s], sqlite3_errmsg(db));
        failures++;
      } else {
        int len = sqlite3_column_bytes(to_wkb, 0);
        unsigned char *wkb = malloc(len > 0 ? len : 1);
        memcpy(wkb, sqlite3_column_blob(to_wkb, 0), len);
        failures += fuzz_buffer(stmts, wkb, len, 1, random_iters);
        free(wkb);
      }
      sqlite3_reset(to_wkb);
      sqlite3_clear_bindings(to_wkb);
    }
    sqlite3_finalize(to_wkb);
  }

  for (int s = 0; s < sizeof(FUZZ_SEED_WKTS) / sizeof(FUZZ_SEED_WKTS[0]);
       s++) {
    failures += fuzz_buffer(stmts, (const unsigned char *)FUZZ_SEED_WKTS[s],
                            (int)strlen(FUZZ_SEED_WKTS[s]), 0, random_iters);
  }
  for (int s = 0;
       s < sizeof(FUZZ_SEED_GEOJSON) / sizeof(FUZZ_SEED_GEOJSON[0]); s++) {
    failures += fuzz_buffer(stmts, (const unsigned char *)FUZZ_SEED_GEOJSON[s],
                            (int)strlen(FUZZ_SEED_GEOJSON[s]), 0,
                            random_iters);
  }

done:
  for (int i = 0; i < FUZZ_QUERY_COUNT; i++) {
    sqlite3_finalize(stmts[i]);
  }
  return failures;
}

// ─────────────────────────────── OOM sweep ─────────────────────────────────
//
// For every N until a full pass survives: open a fresh database, arm the
// injector so the Nth tg allocation fails, run a scenario touching every
// ownership pattern, close, and require zero live tg allocations. Any N that
// crashes, leaks, or wedges the connection is a bug in an OOM error path.

static const char *OOM_SCENARIO[] = {
    "select tg_to_wkt(tg_point(1, 2))",
    "select tg_to_wkb(tg_geom('POLYGON((0 0, 10 0, 10 10, 0 10, 0 0), "
    "(1 1, 2 1, 2 2, 1 2, 1 1))', 'natural'))",
    "select tg_to_geojson(tg_group_multipoint(tg_point(value, value))) "
    "from json_each('[1, 2, 3, 4]')",
    "select tg_to_wkt(tg_group_polygon(value)) from json_each("
    "'[\"POLYGON((0 0, 10 0, 10 10, 0 10, 0 0))\"]')",
    "select tg_to_wkt(point) from tg_ring_points_each("
    "'POLYGON((0 0, 10 0, 10 10, 0 0))')",
    "select tg_to_wkt('not a geometry')", // error path under OOM too
    // tg0 CREATE/table_xinfo/DROP only: this sweeps the constructor parse and
    // tg0_free paths of the typed-column syntax. INSERT/SELECT are stubbed
    // out mid-rewrite; write/read coverage returns in tickets 03/04.
    "create virtual table temp.oom using tg0(label text, shape geometry)",
    "select * from pragma_table_xinfo('oom')",
    "drop table temp.oom",
};

// returns failures; *out_n is the N where a pass first ran injection-free,
// or 0 if the cap was hit first
static int oom_sweep(long cap, long *out_n) {
  *out_n = 0;
  for (long n = 1; n <= cap; n++) {
    sqlite3 *db = NULL;
    if (sqlite3_open(":memory:", &db) != SQLITE_OK) {
      fprintf(stderr, "❌ oom sweep: cannot open database at n=%ld\n", n);
      sqlite3_close(db);
      return 1;
    }
    oom_fired = 0;
    oom_remaining = n;
    for (int i = 0; i < sizeof(OOM_SCENARIO) / sizeof(OOM_SCENARIO[0]); i++) {
      char *err = NULL;
      sqlite3_exec(db, OOM_SCENARIO[i], NULL, NULL, &err);
      sqlite3_free(err);
    }
    oom_remaining = -1;
    int fired = oom_fired;
    if (sqlite3_close(db) != SQLITE_OK) {
      fprintf(stderr, "❌ oom sweep: close failed at n=%ld: %s\n", n,
              sqlite3_errmsg(db));
      return 1;
    }
    if (tg_live != 0) {
      fprintf(stderr,
              "❌ oom sweep: %ld tg allocation(s) leaked when allocation "
              "%ld failed\n",
              tg_live, n);
      return 1;
    }
    if (!fired) {
      *out_n = n;
      return 0;
    }
  }
  return 0;
}

