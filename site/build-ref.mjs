// Generates site/api-reference.md from ../reference.yaml.
// Run with `npm run ref` (also wired into `npm run docs:build`).
//
// Unlike sqlite-vec's build-ref.mjs, this does NOT execute the SQL examples —
// expected results are kept inline as `--` comments in reference.yaml.
import { load } from "js-yaml";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";
import { readFileSync, writeFileSync } from "node:fs";

const DIR = dirname(fileURLToPath(import.meta.url));
const REF_PATH = resolve(DIR, "..", "reference.yaml");
const OUT_PATH = join(DIR, "api-reference.md");

const HEADER = `---
# Generated by build-ref.mjs from reference.yaml — do not edit directly.
outline: [2, 3]
---

<style>
  h3 {font-family: monospace}
  .VPDocOutlineItem.nested {font-family: monospace}
</style>

# API Reference

A complete reference to all the SQL scalar functions, aggregate functions,
table functions, and virtual tables inside \`sqlite-tg\`.

::: warning
\`sqlite-tg\` is pre-v1, so expect breaking changes.
:::

`;

const doc = load(readFileSync(REF_PATH, "utf8"));

if (!doc || typeof doc.sections !== "object") {
  throw new Error(`${REF_PATH} is missing a top-level "sections" map`);
}

// Every non-"sections" top-level key must be a declared section, and vice
// versa — catches typos and orphaned sections.
const sectionIds = Object.keys(doc.sections);
for (const key of Object.keys(doc)) {
  if (key !== "sections" && !sectionIds.includes(key)) {
    throw new Error(`Top-level key "${key}" is not declared in "sections"`);
  }
}

let md = HEADER;

for (const id of sectionIds) {
  const { title, desc } = doc.sections[id];
  const entries = doc[id];
  if (!entries || typeof entries !== "object") {
    throw new Error(`Section "${id}" has no function entries`);
  }

  md += `## ${title} {#${id}}\n\n`;
  if (desc && desc.trim()) {
    md += desc.trim() + "\n\n";
  }

  for (const [name, entry] of Object.entries(entries)) {
    if (!entry || typeof entry.desc !== "string" || !entry.desc.trim()) {
      throw new Error(`"${name}" in section "${id}" is missing a desc`);
    }
    const signature =
      entry.signature ?? `${name}(${(entry.params ?? []).join(", ")})`;
    md += `### \`${signature}\` {#${name}}\n\n`;
    md += entry.desc.trim() + "\n\n";
    if (entry.example && entry.example.trim()) {
      md += "```sql\n" + entry.example.trimEnd() + "\n```\n\n";
    }
  }
}

writeFileSync(OUT_PATH, md, "utf8");
console.log(`wrote ${OUT_PATH}`);
